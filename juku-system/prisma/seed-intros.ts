async function run() {
  const ROLLBACK = Symbol("dry-run-rollback");
  const stats = {
    deletedReads: 0,
    deletedArticles: 0,
    createdArticles: [] as { id: string; title: string }[],
  };

  try {
    await prisma.$transaction(async (tx) => {
      // 1) 既存 Article をすべて削除（ArticleRead は ON DELETE CASCADE で連動）
      const r1 = await tx.articleRead.deleteMany({});
      stats.deletedReads = r1.count;
      const r2 = await tx.article.deleteMany({});
      stats.deletedArticles = r2.count;

      // 2) 新しい 5 件を投入
      for (const a of intros) {
        const created = await tx.article.create({
          data: {
            title: a.title,
            body: a.body,
            audience: a.audience,
            category: a.category,
            images: "[]",
            publishedAt: TODAY,
          },
          select: { id: true, title: true },
        });
        stats.createdArticles.push(created);
      }

      if (dryRun) throw ROLLBACK;
    }, { timeout: 60000 });
  } catch (e) {
    if (e === ROLLBACK) {
      console.log("=== DRY RUN COMPLETE (rolled back) ===");
      console.log(JSON.stringify({
        wouldDelete: { articleReads: stats.deletedReads, articles: stats.deletedArticles },
        wouldCreate: stats.createdArticles.map((a) => a.title),
      }, null, 2));
      return;
    }
    throw e;
  }

  const ts = new Date().toISOString().replace(/[:.]/g, "-");
  const path = resolve(process.cwd(), `prisma/.intros-replaced-${ts}.json`);
  writeFileSync(path, JSON.stringify({ replacedAt: new Date().toISOString(), ...stats }, null, 2));
  console.log("=== COMMIT COMPLETE ===");
  console.log(`Log: ${path}`);
  console.log(JSON.stringify({
    deleted: { articleReads: stats.deletedReads, articles: stats.deletedArticles },
    created: stats.createdArticles.map((a) => a.title),
  }, null, 2));
}

run()
  .then(() => prisma.$disconnect())
  .catch(async (e) => {
    console.error(e);
    await prisma.$disconnect();
    process.exit(1);
  });
